object MusicRepository {
    // Se guardan IDs de favoritos
    private val favoriteSongs = mutableSetOf<Int>()

    fun isFavorite(id: Int) = favoriteSongs.contains(id)

    fun toggleFavorite(song: MusicLocalModel) {
        if (favoriteSongs.contains(song.id)) {
            favoriteSongs.remove(song.id)
            song.isLiked = false
        } else {
            favoriteSongs.add(song.id)
            song.isLiked = true
        }
    }

    fun getFavorites(): List<MusicLocalModel> {
        return MusicResourcesDataSource.myPlaylists
            .flatMap { it.musics }
            .filter { it.isLiked }
    }
}
